const tables: Record<Language, Dict> = { en, de };

export function t(lang: Language, key: string, vars?: Record<string, string | number>): string {
  const template = tables[lang][key] ?? tables.en[key] ?? key;
  if (!vars) return template;
  return Object.entries(vars).reduce(
    (text, [name, value]) => text.split(`{${name}}`).join(String(value)),
    template,
  );
}

export function mapName(lang: Language, id: ArenaMapId): string {
  return t(lang, `map_${id}`);
}

export function mapDesc(lang: Language, id: ArenaMapId): string {
  return t(lang, `mapDesc_${id}`);
}

export function paintName(lang: Language, id: PaintId): string {
  return t(lang, `paint_${id}`);
}

export function hazardTitle(lang: Language, kind: HazardKind): string {
  return t(lang, `hazard_${kind}_title`);
}

export function hazardBody(lang: Language, kind: HazardKind): string {
  return t(lang, `hazard_${kind}_body`);
}
